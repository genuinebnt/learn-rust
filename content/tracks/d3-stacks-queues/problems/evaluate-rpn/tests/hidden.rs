use solution::*;

#[test]
fn long() {
    check!(r#"["10","6","9","3","+","-11","*","/","*","17","+","5","+"]"#, eval_rpn(&["10", "6", "9", "3", "+", "-11", "*", "/", "*", "17", "+", "5", "+"]), 22);
}

#[test]
fn single() {
    check!(r#"["-7"]"#, eval_rpn(&["-7"]), -7);
}

#[test]
fn order_matters() {
    check!(r#"["3","5","-"]"#, eval_rpn(&["3", "5", "-"]), -2);
}
